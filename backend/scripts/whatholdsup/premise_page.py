#!/usr/bin/env python3
"""The premise page (Fred's decision of 2026-11-28 07:02 ET, relayed by the advisor; deviations.md).

When the premise's kill condition is met on the evidence (premise.json kill_condition_tested.result "killed"), WHU
publishes a page saying so instead of stopping Not Ready. It gives NO answer to the original question.

CONTENT, every sentence bound or generated, and checked as on any WHU page:
  * the question restatement (lean_sentences, unchanged);
  * the premise, as the question assumed it: PREMISE_LEAD, then each sentence of the belief recorded before reading
    (premise.json belief.statement) in BELIEF_FRAME -- generated by code from the record (lean_sentences.generate),
    settled by the record check, never written by a model;
  * what the held sources show instead: the full page's own sentences whose binding lies on a premise-reading
    evidence span (EVIDENCE_FIELDS: the kill condition's evidence first) -- sentences already bound, audited and
    passed by the overstatement check; nothing new is written;
  * the conclusion, CONCLUSION, code-written and generated, never "the premise is false";
  * the limits block and the readers' list, regenerated from the records.

THE RULES (preflight row ROW, under lean; premise.py's "premise survived" row passes on a premise page and on
nothing else). A premise page STOPs unless: the kill condition was tested and met; the record's kill evidence is
stated by a sentence on the page bound inside its span (B19 bindings) whose overstatement record says it does not
overstate (a premise is not dismissed by an overstated sentence); every prose sentence on the page is one the full
page carried and the record lists as kept; the conclusion is on the page exactly once; no answer or verdict section
is on the page. Every other preflight row applies unchanged; any other STOP is Not Ready, as before.

Sentences of the full page left off are recorded off the page (off_page_by "premise_page"); a headline unit or
judgement one of them stated is code's readers'-list line PREMISE_STATE (coverage_check.removed_units /
removed_judgements), not counted against the budget.

    python3 premise_page.py <slug> check     the preflight row
"""
from __future__ import annotations

import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

OK, BAD = "ok", "BLOCKED"
ROW = "premise page: the kill condition's evidence is stated and checked"
RECORD = "premise_page.json"
OFF_BY = "premise_page"
PREMISE_LEAD = ("This question rested on a premise: that the primary sources would show a material gap, "
                "overstatement or understatement between them and the belief we recorded before reading them.")
BELIEF_FRAME = "The belief we recorded: “%s”"
CONCLUSION = "The evidence we hold does not support this premise."
LEADS = ("This question rested on a premise: ", "The belief we recorded: “", CONCLUSION)
EVIDENCE_FIELDS = (("kill_condition_tested", "the kill condition's evidence"),
                   ("what_the_sources_show", "what the sources show"),
                   ("direction", "the direction's evidence"))
HEADINGS = ("The premise", "What the sources we hold show instead", "What we conclude")
ANSWER_SECTIONS = ("answer", "findings", "verdict")


def _sha(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def marked(case: Path) -> dict | None:
    """The case's premise-page record, or None: the case's page is a full page."""
    p = Path(case) / RECORD
    try:
        return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None
    except ValueError:
        return {"unreadable": True}


def killed(premise: dict) -> bool:
    t = (premise or {}).get("kill_condition_tested") or {}
    return t.get("result") == "killed" and bool(t.get("by"))


def premise_sentences(premise: dict) -> list[dict]:
    """[{kind, field, sentence}] the premise block and the conclusion, from premise.json (lean_sentences.generate)."""
    import source_ledger as ledger
    out = [{"kind": "premise", "source": None, "field": "premise_page.PREMISE_LEAD", "sentence": PREMISE_LEAD}]
    belief = " ".join((((premise or {}).get("belief") or {}).get("statement") or "").split())
    for s in ledger.sentences(belief):
        s = " ".join(s.split())
        if s:
            out.append({"kind": "premise", "source": None, "field": "premise.json belief.statement",
                        "sentence": BELIEF_FRAME % s})
    out.append({"kind": "premise", "source": None, "field": "premise_page.CONCLUSION", "sentence": CONCLUSION})
    return out


def evidence_spans(premise: dict) -> list[dict]:
    out = []
    for field, what in EVIDENCE_FIELDS:
        ev = ((premise or {}).get(field) or {}).get("evidence") or {}
        if ev.get("source") and ev.get("offsets"):
            out.append({"field": field, "what": what, "source": ev["source"], "at": list(ev["offsets"])})
    return out


def _inside_or_over(at: list, span: list) -> bool:
    return at[0] < span[1] and span[0] < at[1]


def stating(rows: dict, held: dict, span: dict) -> list[tuple[str, dict]]:
    """[(fingerprint, row)] of on-page body bindings whose located span overlaps SPAN."""
    import audit_stage as A
    import bindings as B
    import ruling as R
    out = []
    for fp, r in rows.items():
        if not r.get("on_page") or B.is_declaration_row(r):
            continue
        for sid, q in R.quotations(r, held):
            at = A.locate(q, held.get(sid) or "")
            if sid == span["source"] and at and _inside_or_over(list(at), span["at"]):
                out.append((fp, r))
                break
    return out


def overstatement_ok(case: Path, sentence: str) -> bool:
    """The sentence has an overstatement record, and every record for it says it does not overstate."""
    from orch.page import fingerprint
    p = Path(case) / "rulings" / "overstatement.jsonl"
    if not p.exists():
        return False
    fp = fingerprint(sentence)
    got = [json.loads(ln) for ln in p.read_text(encoding="utf-8").splitlines() if ln.strip()]
    got = [g for g in got if g.get("sentence_sha") == fp]
    return bool(got) and all(g.get("verdict") == "no" for g in got)


# ---------------------------------------------------------------- the build (code only)

def build(ctx) -> dict:
    """Turn CTX's full page into the premise page, by code from the records: page.json, the html, the bindings
    (sentences left off go off the page, off_page_by OFF_BY) and the record RECORD. No model call."""
    import bindings as B
    import premise as PM
    import ruling as R
    from orch.page import Page, fingerprint, norm
    import orchestrator as O
    case, slug = ctx.case, ctx.slug
    premise = PM.load(slug) or {}
    if not killed(premise):
        raise SystemExit("premise_page: the kill condition was not met; this is not a premise page")
    held = R.held_texts(slug)
    doc_b = B.load(slug)
    rows = doc_b.get("bindings") or {}
    full = json.loads(ctx.page_json.read_text(encoding="utf-8"))
    spans = evidence_spans(premise)
    keep: dict[str, str] = {}
    for sp in spans:
        for fp, r in stating(rows, held, sp):
            keep.setdefault(fp, sp["field"])
    blocks = full["blocks"]
    body = [norm(s) for b in blocks if b.get("tag") == "p" for s in b.get("sentences") or []]
    kept = [s for s in body if fingerprint(s) in keep]
    dropped = [s for s in body if fingerprint(s) not in keep]

    def sec(name):
        return [b for b in blocks if b.get("section") == name]
    new = sec("question")
    new += [{"tag": "h2", "section": "premise", "text": HEADINGS[0]},
            {"tag": "html", "section": "premise", "html": ""}]
    new += [{"tag": "h2", "section": "instead", "text": HEADINGS[1]}]
    if kept:
        new.append({"tag": "p", "section": "instead", "sentences": kept})
    new += [{"tag": "h2", "section": "conclusion", "text": HEADINGS[2]},
            {"tag": "html", "section": "conclusion", "html": ""}]
    new += sec("limits") + sec("readers") + sec("sources")
    page_doc = dict(full, blocks=new, kind="premise_page",
                    provenance={k: v for k, v in (full.get("provenance") or {}).items() if norm(k) in kept})
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    off = "%s:%s" % (OFF_BY, stamp)
    for fp, r in rows.items():
        if r.get("on_page") and not B.is_declaration_row(r) and norm(r.get("sentence") or "") in set(dropped):
            r["on_page"] = False
            r["off_page_by"] = off
    B.save(slug, doc_b) if hasattr(B, "save") else B.path(slug).write_text(
        json.dumps(doc_b, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    rec = {"built_at": stamp, "by": "code (premise_page.build; Fred's decision of 2026-11-28, relayed)",
           "from_page_sha256": _sha(ctx.page.read_text(encoding="utf-8")),
           "evidence": spans, "kept": {fingerprint(s): keep[fingerprint(s)] for s in kept},
           "dropped": [fingerprint(s) for s in dropped]}
    (case / RECORD).write_text(json.dumps(rec, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    page = Page(page_doc)
    import lean_sentences as LS
    import html as H
    gen = premise_sentences(premise)
    page.set_html("premise", "".join("  <p>%s</p>\n" % H.escape(g["sentence"], quote=False) for g in gen[:-1]))
    page.set_html("conclusion", "  <p>%s</p>\n" % H.escape(CONCLUSION, quote=False))
    page.save(ctx.page_json)
    ctx.page.write_text(O._render(ctx, page), encoding="utf-8")   # first: the readers' list reads this page's body
    O._rerender(ctx, Page.load(ctx.page_json))
    import quotations as Q
    q = Q.match_held(slug, ctx.page)                                # the quotation step: code from held text alone
    return {"quotations_matched": q["matched"], "quotations_unmatched": len(q["unmatched"]),"kept": len(kept), "dropped": len(dropped), "evidence": spans,
            "kept_by_span": sorted(set(keep.values()))}


# ---------------------------------------------------------------- the row

def preflight_rows(slug: str, page_sentences: list[str] | None = None) -> list[tuple[str, str, str]]:
    import bindings as B
    import premise as PM
    import ruling as R
    import source_store as store
    from orch.page import fingerprint, norm
    case = store.case_dir(slug)
    rec = marked(case)
    if rec is None:
        return []
    if rec.get("unreadable"):
        return [(ROW, BAD, "%s does not parse" % RECORD)]
    premise = PM.load(slug) or {}
    bad = []
    if not killed(premise):
        bad.append("the kill condition was not tested and met, so this cannot be a premise page")
    ps = [norm(s) for s in (page_sentences if page_sentences is not None else B.page_sentences(slug))]
    pj = json.loads((case / "draft" / "page.json").read_text(encoding="utf-8"))
    if pj.get("kind") != "premise_page":
        bad.append("draft/page.json is not marked as a premise page")
    if any(b.get("section") in ANSWER_SECTIONS for b in pj.get("blocks") or []):
        bad.append("the page carries an answer or verdict section")
    body = [norm(s) for b in pj.get("blocks") or [] if b.get("tag") == "p" for s in b.get("sentences") or []]
    stray = [s for s in body if fingerprint(s) not in (rec.get("kept") or {})]
    if stray:
        bad.append("%d prose sentence(s) the record does not list as kept from the full page (e.g. %r)"
                   % (len(stray), stray[0][:80]))
    missing = [g["sentence"] for g in premise_sentences(premise)[:-1] if norm(g["sentence"]) not in ps]
    if missing:
        bad.append("%d premise sentence(s) from the record not on the page (e.g. %r)" % (len(missing), missing[0][:80]))
    if ps.count(CONCLUSION) != 1:
        bad.append("the conclusion %r is on the page %d time(s), not once" % (CONCLUSION, ps.count(CONCLUSION)))
    held = R.held_texts(slug)
    rows = B.load(slug).get("bindings") or {}
    spans = evidence_spans(premise)
    kill = [s for s in spans if s["field"] == "kill_condition_tested"]
    if not kill:
        bad.append("the kill condition's test records no evidence span")
    shown = 0
    for sp in spans:
        st = [(fp, r) for fp, r in stating(rows, held, sp) if norm(r.get("sentence") or "") in ps]
        good = [r for fp, r in st if overstatement_ok(case, r.get("sentence") or "")]
        if good:
            shown += 1
        elif sp["field"] == "kill_condition_tested":
            bad.append("the kill condition's evidence (%s@%d-%d) is stated by no sentence on the page that is bound "
                       "to it and passed the overstatement check%s"
                       % (sp["source"], sp["at"][0], sp["at"][1],
                          " (%d bound, none with a passing overstatement record)" % len(st) if st else ""))
    if bad:
        return [(ROW, BAD, "; ".join(bad))]
    return [(ROW, OK, "the kill condition was met; %d of %d evidence span(s) stated by bound sentences that passed "
             "the overstatement check; %d sentence(s) kept from the full page; no answer given"
             % (shown, len(spans), len(body)))]


def main(argv=None) -> int:
    a = list(sys.argv[1:] if argv is None else argv)
    if len(a) != 2 or a[1] != "check":
        print(__doc__)
        return 2
    for row in preflight_rows(a[0]) or [(ROW, OK, "not a premise page")]:
        print("  %-6s %-40s %s" % (row[1], row[0], row[2]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
