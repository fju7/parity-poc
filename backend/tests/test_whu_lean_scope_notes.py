FIX = json.loads((ROOT / "backend" / "tests" / "fixtures" / "whu_lean" / "round1_scope_notes.json")
                 .read_text(encoding="utf-8"))["questions"]
SLUGS = sorted(FIX)


@pytest.fixture
def lean_on(monkeypatch):
    monkeypatch.delenv(lean.ENV_MODELS, raising=False)
    lean.enable(True)
    yield
    lean.enable(False)
    lean._forced = None


def _gen(slug):
    q = FIX[slug]
    return LS.generate({"question": q["question"]}, q["sources"], q["search"], q["declared"])


def _units(sentences):
    return [{"id": "u%d" % i, "part": "page", "sentence": s, "sha": A.fingerprint(s), "row": None}
            for i, s in enumerate(sentences, 1)]


def test_the_fixture_is_round_ones_four_questions_and_their_65_scope_reads():
    assert SLUGS == ["whu-quarterly-r1-0%d" % i for i in (1, 2, 3, 4)]
    reads = {s: FIX[s]["round1_person_reads"] for s in SLUGS}
    assert [len(reads[s]) for s in SLUGS] == [5, 10, 34, 32]
    assert [len([r for r in reads[s] if r["kind"] == "scope"]) for s in SLUGS] == [2, 5, 29, 29]
    # every person read in round 1 was a protected sentence; none was a licensed-source read
    assert all(r["kind"] for s in SLUGS for r in reads[s])
    assert not any(r["licensed"] for s in SLUGS for r in reads[s])


@pytest.mark.parametrize("slug", SLUGS)
def test_every_generated_sentence_is_one_sentence_and_protected(slug):
    for g in _gen(slug):
        assert not g.get("splits"), g["sentence"]
        assert B.protected_kind(g["sentence"]), g["sentence"]
        assert LS.is_framed(g["sentence"]), g["sentence"]


@pytest.mark.parametrize("slug", SLUGS)
def test_readers_list_lines_carry_no_reason_clause(slug):
    for d in FIX[slug]["declared"]:
        if d["state"] == "not_added_cap":
            continue
        assert d["sentence"].endswith(").") and "); " not in d["sentence"], d["sentence"]


@pytest.mark.parametrize("slug", SLUGS)
def test_zero_sentences_routed_to_a_person_and_audit_complete_passes_without_a_person_read(slug, tmp_path, lean_on,
                                                                                           monkeypatch):
    gen = _gen(slug)
    monkeypatch.setattr(LS, "generated", lambda s: gen)
    us = _units([g["sentence"] for g in gen])
    fake = Fake()
    m = A.run(slug, out_dir=tmp_path, ask=fake, held={}, unit_list=us, cap=1.0, licensed=set())
    assert m["status"] == "complete"
    states = [m["state"][u["sha"]] for u in us]
    assert A.HUMAN_READ_REQUIRED not in states
    assert set(states) == {LS.RECORD_CHECK}
    assert not fake.prompts                                    # no model read a protected sentence
    assert not (tmp_path / "human_reads.jsonl").exists()
    row = A.preflight_rows(slug, [], current=us, run_dir=tmp_path)
    assert row[0][1] == A.OK, row
    assert LS.check([g["sentence"] for g in gen], gen)[1] == LS.OK


@pytest.mark.parametrize("slug", SLUGS)
def test_round_ones_hand_written_protected_sentences_must_leave_and_none_goes_to_a_person(slug, tmp_path, lean_on,
                                                                                          monkeypatch):
    gen = _gen(slug)
    monkeypatch.setattr(LS, "generated", lambda s: gen)
    hand = [r["sentence"] for r in FIX[slug]["round1_person_reads"] if not LS.matches(r["sentence"], gen)]
    assert hand
    us = _units(hand)
    m = A.run(slug, out_dir=tmp_path, ask=Fake(), held={}, unit_list=us, cap=1.0, licensed=set())
    states = [m["state"][u["sha"]] for u in us]
    assert A.HUMAN_READ_REQUIRED not in states
    assert set(states) == {"must_leave_page"}
    row = A.preflight_rows(slug, [], current=us, run_dir=tmp_path)
    assert row[0][1] == A.BAD and "need a person" not in row[0][2]
    # and the record check stops while one is on the page
    assert LS.check([g["sentence"] for g in gen] + hand[:1], gen)[1] == LS.BAD


def test_search_frames_come_from_the_search_record():
    s = [g["sentence"] for g in LS.generate({"question": "Q?"}, [], {"searched": ["the web, on 1 May 2026"],
                                                                     "not_searched": ["trial registries"]})]
    assert "We searched: the web, on 1 May 2026." in s
    assert "We did not search: trial registries." in s


def test_off_lean_a_protected_sentence_still_goes_to_a_person(tmp_path):
    lean.enable(False)
    s = "We did not search for trials published after 2020."
    us = _units([s])
    m = A.run("demo", out_dir=tmp_path, ask=Fake(), held={}, unit_list=us, cap=1.0, licensed=set())
    assert m["state"][us[0]["sha"]] == A.HUMAN_READ_REQUIRED
    lean._forced = None


def test_off_lean_the_readers_list_line_keeps_its_reason():
    line = C.declaration_sentence("out_of_scope", "A finding.", "Review [1]", "about adults, not children")
    assert line == "Outside this question: “A finding.” (Review [1]); about adults, not children."
    assert C.declaration_sentence("out_of_scope", "A finding.", "Review [1]", None) == \
        "Outside this question: “A finding.” (Review [1])."


