"""Lean + machine scope notes (process doc §4.6.1; advisor's ruling, 4-5 November 2026).

Under WHU_LEAN=1 every protected sentence -- the question, what we held, read and
searched, and the readers' list of declared findings -- is generated by code from
the run's records, and none is routed to a person. Tested on round 1's four WHU
questions (fixtures/whu_lean/round1_scope_notes.json, built at $0 from their
records; its search lists are transcribed, as the fixture says). No model is
called: the audit runs with a fake `ask`.
"""
